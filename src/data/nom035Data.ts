// Función auxiliar para determinar el riesgo
export const determinarRiesgo = (puntaje: number, rangos: number[]) => {
  if (puntaje < rangos[0]) return 'Nulo';
  if (puntaje < rangos[1]) return 'Bajo';
  if (puntaje < rangos[2]) return 'Medio';
  if (puntaje < rangos[3]) return 'Alto';
  return 'Muy alto';
};
